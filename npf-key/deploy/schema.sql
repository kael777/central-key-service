CREATE TABLE IF NOT EXISTS KEY_SECRET (
    ID             BIGINT AUTO_INCREMENT PRIMARY KEY,
    KEY_NAME       VARCHAR(64)  NOT NULL,
    KEY_TYPE       VARCHAR(16)  NOT NULL,
    VERSION        INT          NOT NULL,
    KEY_ID         CHAR(16)     NOT NULL,
    STATUS         VARCHAR(16)  NOT NULL,
    CIPHER_TEXT    VARBINARY(512) NOT NULL,
    KMS_KEY_ID     VARCHAR(128),
    CREATED_AT     TIMESTAMP(6) NOT NULL,
    UPDATED_AT     TIMESTAMP(6) NOT NULL,
    ROTATED_AT     TIMESTAMP(6),
    REMARK         VARCHAR(255),
    ROTATE_ENABLED TINYINT      NOT NULL DEFAULT 1,
    CONSTRAINT UK_KEY_VERSION UNIQUE (KEY_NAME, VERSION)
);



CREATE TABLE IF NOT EXISTS KEY_AUDIT_LOG (
    ID          BIGINT AUTO_INCREMENT PRIMARY KEY,
    OCCURRED_AT TIMESTAMP(6) NOT NULL,
    ACTION      VARCHAR(32)  NOT NULL,
    CLIENT_ID   VARCHAR(64),
    KEY_NAME    VARCHAR(64),
    VERSION     INT,
    SOURCE_IP   VARCHAR(64),
    REASON      VARCHAR(255)
);


